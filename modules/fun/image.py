import aiohttp
import urllib.parse
import io
from telethon import events

def register(client):
    
    @client.on(events.NewMessage(outgoing=True, pattern=r'(?i)^\.imagine (.*)'))
    async def imagine_handler(event):
        prompt = event.pattern_match.group(1).strip()
        if not prompt:
            return await event.edit("❌ **Usage:** `.imagine <your prompt>`\nExample: `.imagine a cyberpunk cat`")
        
        # Process start message
        status_msg = await event.edit("🎨 **Generating image... Please wait.**")
        
        # Encode prompt for URL
        encoded_prompt = urllib.parse.quote(prompt)
        
        # 🔥 Free API URL with enhance=true (Auto-enhances prompt for DALL-E like quality)
        url = f"https://image.pollinations.ai/prompt/{encoded_prompt}?width=1024&height=1024&nologo=true&enhance=true"
        
        try:
            # Use aiohttp to download image bytes directly (Saves RAM & Disk)
            async with aiohttp.ClientSession() as session:
                async with session.get(url, timeout=45) as response:
                    if response.status == 200:
                        image_bytes = await response.read()
                        
                        photo = io.BytesIO(image_bytes)
                        photo.name = "image.jpg"
                        
                        await client.send_file(
                            event.chat_id,
                            photo,
                            caption=f"✨ **Prompt:** `{prompt}`\n🤖 **Generated by Empire AI**",
                            reply_to=event.reply_to_msg_id if event.is_reply else None
                        )
                        
                        await status_msg.delete()
                    else:
                        await status_msg.edit(f"❌ **API Error:** Failed to generate image. (Status: {response.status})")
                        
        except Exception as e:
            await status_msg.edit(f"❌ **Error:** `{str(e)}`")
